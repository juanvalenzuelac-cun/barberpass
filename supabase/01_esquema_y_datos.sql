-- ---------------------------------------------------------------------
-- 1. PLAN: planes de suscripción que BarberPass vende a las barberías
-- ---------------------------------------------------------------------
CREATE TABLE plan (
    id_plan         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(30)   NOT NULL UNIQUE,
    precio_mensual  DECIMAL(10,2) NOT NULL CHECK (precio_mensual >= 0),
    max_barberos    SMALLINT      NOT NULL CHECK (max_barberos > 0)
);

-- ---------------------------------------------------------------------
-- 2. BARBERIA: cada negocio cliente de la plataforma (multiempresa)
--    La dirección es un atributo compuesto -> calle, barrio, ciudad
-- ---------------------------------------------------------------------
CREATE TABLE barberia (
    id_barberia     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nit             VARCHAR(15)  NOT NULL UNIQUE,
    nombre          VARCHAR(80)  NOT NULL,
    dir_calle       VARCHAR(80)  NOT NULL,
    dir_barrio      VARCHAR(50),
    dir_ciudad      VARCHAR(40)  NOT NULL,
    color_primario  CHAR(7)      NOT NULL DEFAULT '#000000'
                    CHECK (color_primario ~ '^#[0-9A-Fa-f]{6}$'),
    color_secundario CHAR(7)     NOT NULL DEFAULT '#C9A35B'
                    CHECK (color_secundario ~ '^#[0-9A-Fa-f]{6}$'),
    logo_url        VARCHAR(200),
    id_plan         INT          NOT NULL REFERENCES plan(id_plan),
    fecha_registro  DATE         NOT NULL,
    activa          BOOLEAN      NOT NULL DEFAULT TRUE
);

-- ---------------------------------------------------------------------
-- 3. TELEFONO_BARBERIA: atributo multivalorado de BARBERIA (entidad débil)
-- ---------------------------------------------------------------------
CREATE TABLE telefono_barberia (
    id_barberia     INT          NOT NULL REFERENCES barberia(id_barberia) ON DELETE CASCADE,
    telefono        VARCHAR(15)  NOT NULL,
    tipo            VARCHAR(10)  NOT NULL CHECK (tipo IN ('FIJO','CELULAR','WHATSAPP')),
    PRIMARY KEY (id_barberia, telefono)
);

-- ---------------------------------------------------------------------
-- 4. EMPLEADO: barberos y gerentes de cada barbería
--    usuario + PIN de 4 dígitos para entrar a la app del barbero.
--    El PIN nunca se guarda: pin_hash = SHA-256 de 'usuario:PIN'.
-- ---------------------------------------------------------------------
CREATE TABLE empleado (
    id_empleado     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_barberia     INT          NOT NULL REFERENCES barberia(id_barberia),
    documento       VARCHAR(15)  NOT NULL UNIQUE,
    nombres         VARCHAR(50)  NOT NULL,
    apellidos       VARCHAR(50)  NOT NULL,
    celular         VARCHAR(15)  NOT NULL,
    usuario         VARCHAR(30)  NOT NULL UNIQUE CHECK (usuario ~ '^[a-z0-9._]{3,30}$'),
    pin_hash        CHAR(64)     NOT NULL,
    rol             VARCHAR(10)  NOT NULL CHECK (rol IN ('BARBERO','GERENTE')),
    fecha_ingreso   DATE         NOT NULL,
    activo          BOOLEAN      NOT NULL DEFAULT TRUE
);

-- ---------------------------------------------------------------------
-- 5. CREDENCIAL: medio con el que el barbero registra los sellos
--    NFC = tarjeta física con chip que el barbero acerca al celular del cliente
--    QR  = código QR dinámico que muestra la app del barbero; el cliente lo
--          escanea con la cámara (para celulares sin NFC o con NFC apagado).
--          El QR se regenera cada 30 s y sirve una sola vez.
--    identificador = UID de fábrica del chip (NFC) o clave secreta con la que
--          la app genera los QR (QR). Un empleado puede tener varias en el tiempo.
-- ---------------------------------------------------------------------
CREATE TABLE credencial (
    id_credencial    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado      INT          NOT NULL REFERENCES empleado(id_empleado),
    tipo             VARCHAR(3)   NOT NULL CHECK (tipo IN ('NFC','QR')),
    identificador    VARCHAR(64)  NOT NULL UNIQUE,
    fecha_asignacion DATE         NOT NULL,
    estado           VARCHAR(10)  NOT NULL DEFAULT 'ACTIVA'
                     CHECK (estado IN ('ACTIVA','BLOQUEADA','PERDIDA'))
);

-- ---------------------------------------------------------------------
-- 6. CLIENTE: persona que acumula sellos (puede ir a varias barberías)
--    edad = atributo derivado de fecha_nacimiento (no se almacena)
-- ---------------------------------------------------------------------
CREATE TABLE cliente (
    id_cliente       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres          VARCHAR(50)  NOT NULL,
    apellidos        VARCHAR(50)  NOT NULL,
    celular          VARCHAR(15)  NOT NULL UNIQUE,
    correo           VARCHAR(100) UNIQUE,
    fecha_nacimiento DATE,
    fecha_registro   DATE         NOT NULL
);

-- ---------------------------------------------------------------------
-- 7. PROGRAMA_FIDELIZACION: reglas del programa de sellos de cada barbería
--    fecha_fin NULL = programa vigente
-- ---------------------------------------------------------------------
CREATE TABLE programa_fidelizacion (
    id_programa       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_barberia       INT          NOT NULL REFERENCES barberia(id_barberia),
    sellos_requeridos SMALLINT     NOT NULL CHECK (sellos_requeridos BETWEEN 3 AND 20),
    premio            VARCHAR(100) NOT NULL,
    fecha_inicio      DATE         NOT NULL,
    fecha_fin         DATE,
    CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

-- ---------------------------------------------------------------------
-- 8. TARJETA_FIDELIZACION: entidad asociativa CLIENTE N:M BARBERIA
--    Es la tarjeta digital que vive en Apple Wallet / Google Wallet
--    sellos_disponibles = atributo derivado (visitas - sellos canjeados)
-- ---------------------------------------------------------------------
CREATE TABLE tarjeta_fidelizacion (
    id_tarjeta        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente        INT          NOT NULL REFERENCES cliente(id_cliente),
    id_barberia       INT          NOT NULL REFERENCES barberia(id_barberia),
    codigo_wallet     VARCHAR(40)  NOT NULL UNIQUE,
    plataforma_wallet VARCHAR(6)   NOT NULL CHECK (plataforma_wallet IN ('APPLE','GOOGLE')),
    fecha_alta        DATE         NOT NULL,
    UNIQUE (id_cliente, id_barberia)
);

-- ---------------------------------------------------------------------
-- 9. SERVICIO: catálogo de servicios y precios de cada barbería
-- ---------------------------------------------------------------------
CREATE TABLE servicio (
    id_servicio     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_barberia     INT           NOT NULL REFERENCES barberia(id_barberia),
    nombre          VARCHAR(60)   NOT NULL,
    precio          DECIMAL(10,2) NOT NULL CHECK (precio > 0),
    duracion_min    SMALLINT      NOT NULL CHECK (duracion_min BETWEEN 5 AND 240),
    activo          BOOLEAN       NOT NULL DEFAULT TRUE,
    UNIQUE (id_barberia, nombre)
);

-- ---------------------------------------------------------------------
-- 10. VISITA: cada corte registrado; genera exactamente un sello
--     El barbero y el método (NFC o QR) se obtienen de la credencial que
--     selló (3FN: no se repiten aquí)
--     codigo_sello = token único de un solo uso (anti-fraude); en el método QR
--     es el token del código escaneado, así una foto del QR no se puede reutilizar
-- ---------------------------------------------------------------------
CREATE TABLE visita (
    id_visita       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tarjeta      INT          NOT NULL REFERENCES tarjeta_fidelizacion(id_tarjeta),
    id_credencial   INT          NOT NULL REFERENCES credencial(id_credencial),
    fecha_hora      TIMESTAMP    NOT NULL,
    codigo_sello    CHAR(16)     NOT NULL UNIQUE
);

-- ---------------------------------------------------------------------
-- 11. DETALLE_VISITA: asociativa VISITA N:M SERVICIO
--     precio_cobrado guarda el precio histórico del día de la visita
-- ---------------------------------------------------------------------
CREATE TABLE detalle_visita (
    id_visita       INT           NOT NULL REFERENCES visita(id_visita) ON DELETE CASCADE,
    id_servicio     INT           NOT NULL REFERENCES servicio(id_servicio),
    precio_cobrado  DECIMAL(10,2) NOT NULL CHECK (precio_cobrado >= 0),
    PRIMARY KEY (id_visita, id_servicio)
);

-- ---------------------------------------------------------------------
-- 12. CANJE: cuando el cliente cambia sus sellos por el premio
-- ---------------------------------------------------------------------
CREATE TABLE canje (
    id_canje        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tarjeta      INT          NOT NULL REFERENCES tarjeta_fidelizacion(id_tarjeta),
    id_programa     INT          NOT NULL REFERENCES programa_fidelizacion(id_programa),
    id_credencial   INT          NOT NULL REFERENCES credencial(id_credencial),
    fecha_hora      TIMESTAMP    NOT NULL,
    sellos_usados   SMALLINT     NOT NULL CHECK (sellos_usados > 0)
);

-- ---------------------------------------------------------------------
-- 13. ADMINISTRADOR: personas de BarberPass que administran la plataforma
--     (dan de alta barberías, personalizan su marca, gestionan credenciales)
-- ---------------------------------------------------------------------
CREATE TABLE administrador (
    id_admin        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario         VARCHAR(30)  NOT NULL UNIQUE CHECK (usuario ~ '^[a-z0-9._]{3,30}$'),
    nombre          VARCHAR(80)  NOT NULL,
    pin_hash        CHAR(64)     NOT NULL,
    activo          BOOLEAN      NOT NULL DEFAULT TRUE
);

-- ---------------------------------------------------------------------
-- 14. SESION: ingreso a la app del barbero o al panel de administración
--     Pertenece a un empleado O a un administrador, nunca a los dos
--     (arco exclusivo, controlado con el CHECK num_nonnulls = 1).
-- ---------------------------------------------------------------------
CREATE TABLE sesion (
    id_sesion       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token           CHAR(64)     NOT NULL UNIQUE,
    id_empleado     INT          REFERENCES empleado(id_empleado),
    id_admin        INT          REFERENCES administrador(id_admin),
    creada          TIMESTAMP    NOT NULL,
    expira          TIMESTAMP    NOT NULL,
    CHECK (num_nonnulls(id_empleado, id_admin) = 1),
    CHECK (expira > creada)
);

-- Índices para las consultas más frecuentes de la app
CREATE INDEX ix_visita_tarjeta   ON visita(id_tarjeta);
CREATE INDEX ix_visita_fecha     ON visita(fecha_hora);
CREATE INDEX ix_empleado_barb    ON empleado(id_barberia);
CREATE INDEX ix_credencial_emp   ON credencial(id_empleado);


